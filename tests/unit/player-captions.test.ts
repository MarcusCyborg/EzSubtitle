import { afterEach, describe, expect, it, vi } from 'vitest';
import type { CaptionTrack } from '../../src/types/transcript';
import { fromPlayerBundle, observePlayerCaptions } from '../../src/lib/youtube/player-captions';
import { MAX_RESPONSE_BYTES } from '../../src/lib/transcript/bounded-response';

const video = 'AAAAAAAAAAA';
const otherVideo = 'BBBBBBBBBBB';
const origin = 'https://www.youtube.com';
const base = `${origin}/api/timedtext?v=${video}&lang=en&name=Main&variant=one`;
const timedtext = `${base}&fmt=json3`;
const track: CaptionTrack = { id: '.en', baseUrl: base, languageCode: 'en', label: 'Main', isAutoGenerated: false };
const json3 = JSON.stringify({ events: [{ tStartMs: 0, segs: [{ utf8: 'Player cue' }] }] });
// Regression reported by review-player-params.test.ts. Values are synthetic;
// the five option names were observed in local YouTube track metadata.
const metadataOptions = ['exp', 'xoaf', 'xowf', 'xowatf', 'xospf'];

function response(url: string, body: string | ReadableStream<Uint8Array> = json3, status = 200): Response {
  const result = new Response(body, { status });
  Object.defineProperty(result, 'url', { value: url });
  return result;
}

function harness(transport: typeof fetch, caller?: () => boolean) {
  let currentVideo = video;
  let tracks = [track];
  class FakeXHR extends EventTarget {
    responseType = '';
    responseText = '<transcript><text start="0">&#x20BB7;</text></transcript>';
    responseURL = '';
    status = 200;
    open(_method: string, url: string) { this.responseURL = url; }
    send() { this.dispatchEvent(new Event('loadend')); }
    setRequestHeader() { /* Stub the browser method. */ }
    getResponseHeader() { return null; }
  }
  const page = { fetch: transport, location: { origin, href: `${origin}/watch?v=${video}` }, Request, XMLHttpRequest: FakeXHR };
  const observer = observePlayerCaptions(page as unknown as Window & typeof globalThis, () => currentVideo, () => tracks, caller);
  return {
    page, observer, FakeXHR, navigate: (to: string) => { currentVideo = to; }, setTracks: (values: CaptionTrack[]) => { tracks = values; },
  };
}

afterEach(() => vi.restoreAllMocks());

describe('passive player CC capture', () => {
  it.each(metadataOptions)('captures a request with matching metadata option %s', async (key) => {
    const { page, observer, setTracks } = harness(async (input) => response(String(input)), () => true);
    const selected = { ...track, baseUrl: `${base}&${key}=synthetic` };
    setTracks([selected]);
    try {
      await page.fetch(`${selected.baseUrl}&fmt=json3`);
      await vi.waitFor(() => expect(observer.read(video, selected)?.segments).toEqual([{ startMs: 0, text: 'Player cue' }]));
      expect(observer.diagnostics().some(({ result }) => result === 'UNSUPPORTED_REQUEST_SCOPE')).toBe(false);
      setTracks([{ ...selected, baseUrl: `${base}&${key}=changed` }]);
      expect(observer.read(video, selected)).toBeNull();
    } finally { observer.dispose(); }
  });

  it.each(metadataOptions)('rejects missing, different, duplicate or request-only %s values', async (key) => {
    const { page, observer, setTracks } = harness(async (input) => response(String(input)), () => true);
    const selected = { ...track, baseUrl: `${base}&${key}=synthetic` };
    setTracks([selected]);
    try {
      for (const url of [timedtext, `${timedtext}&${key}=other`, `${timedtext}&${key}=synthetic&${key}=other`]) {
        await page.fetch(url);
        expect(observer.read(video, selected)).toBeNull();
        expect(observer.diagnostics().at(-1)?.result).toBe('TRACK_UNCONFIRMED');
      }
      setTracks([track]);
      await page.fetch(`${timedtext}&${key}=synthetic`);
      expect(observer.read(video, track)).toBeNull();
      expect(observer.diagnostics().at(-1)?.result).toBe('TRACK_UNCONFIRMED');
      setTracks([{ ...selected, baseUrl: `${selected.baseUrl}&${key}=synthetic` }]);
      await page.fetch(`${timedtext}&${key}=synthetic`);
      expect(observer.read(video, selected)).toBeNull();
      expect(observer.diagnostics().at(-1)?.result).toBe('TRACK_UNCONFIRMED');
    } finally { observer.dispose(); }
  });

  it('keeps request scope and continuation safeguards with all observed metadata options present', async () => {
    const options = metadataOptions.map((key) => `${key}=synthetic`).join('&');
    const selected = { ...track, baseUrl: `${base}&${options}` };
    const pagedBody = JSON.stringify({ events: [{ tStartMs: 0, segs: [{ utf8: 'Partial' }] }], continuation: 'next' });
    const { page, observer, setTracks } = harness(async (input) => response(String(input), pagedBody), () => true);
    setTracks([selected]);
    const requestUrl = `${selected.baseUrl}&fmt=json3`;
    try {
      for (const key of ['start', 'end', 'range', 'sq', 'continuation', 'unknown']) {
        const rangedTrack = { ...selected, baseUrl: `${selected.baseUrl}&${key}=1` };
        setTracks([rangedTrack]);
        await page.fetch(`${requestUrl}&${key}=1`);
        expect(observer.read(video, rangedTrack)).toBeNull();
        expect(observer.diagnostics().at(-1)?.result).toBe('UNSUPPORTED_REQUEST_SCOPE');
      }
      setTracks([selected]);
      await page.fetch(requestUrl, { headers: { range: 'bytes=0-1000' } });
      expect(observer.diagnostics().at(-1)?.result).toBe('UNSUPPORTED_REQUEST_SCOPE');
      await page.fetch(requestUrl);
      await vi.waitFor(() => expect(observer.diagnostics().at(-1)?.result).toBe('UNSUPPORTED_BODY'));
      expect(observer.read(video, selected)).toBeNull();
    } finally { observer.dispose(); }
  });

  it('requires the direct player bundle caller and bypasses observation for the extension transport', async () => {
    const native = vi.fn(async (input: RequestInfo | URL) => response(String(input)));
    const { page, observer } = harness(native);
    const playerScript = `${origin}/s/player/abc/player_ias.vflset/en_US/base.js`;
    expect(fromPlayerBundle(`    at CaptionLoader (${playerScript}:1:120)`, origin)).toBe(true);
    expect(fromPlayerBundle(`    at loader (https://evil.test/s/player/abc/base.js:1:20)`, origin)).toBe(false);
    expect(fromPlayerBundle('    at loader (chrome-extension://another/player.js:1:20)', origin)).toBe(false);

    // Model a Chromium stack frame for the direct player caller.
    const callFromPlayer = new Function('page', 'url', `return page.fetch(url);\n//# sourceURL=${playerScript}`) as typeof page.fetch;
    await observer.extensionFetch(timedtext);
    expect(observer.diagnostics()).toEqual([]);
    await page.fetch(timedtext);
    expect(observer.diagnostics()).toEqual([{ transport: 'fetch', result: 'INITIATOR_UNCONFIRMED' }]);
    expect(observer.read(video, track)).toBeNull();

    const original = await Reflect.apply(callFromPlayer, null, [page, timedtext]) as Response;
    expect(await original.text()).toBe(json3);
    await vi.waitFor(() => expect(observer.read(video, track)?.segments).toEqual([{ startMs: 0, text: 'Player cue' }]));
    expect(native).toHaveBeenCalledTimes(3);
    observer.dispose();
    expect(page.fetch).toBe(native);
  });

  it.each([
    ['v', otherVideo], ['lang', 'vi'], ['kind', 'asr'], ['tlang', 'vi'], ['name', 'Alternate'],
    ['variant', 'two'], ['track', 'wrong'], ['vssId', '.wrong'], ['start', '30'],
  ])('does not substitute a response with a different or unsupported %s', async (key, value) => {
    const { page, observer } = harness(async (input) => response(String(input)), () => true);
    const url = new URL(timedtext);
    url.searchParams.set(key, value);
    await page.fetch(url.href);
    expect(observer.read(video, track)).toBeNull();
    observer.dispose();
  });

  it('rejects ambiguous metadata even when the URL discriminators are identical', async () => {
    const { page, observer, setTracks } = harness(async (input) => response(String(input)), () => true);
    setTracks([track, { ...track, id: 'other' }]);
    await page.fetch(timedtext);
    expect(observer.diagnostics()).toContainEqual({ transport: 'fetch', format: 'json3', result: 'TRACK_UNCONFIRMED' });
    expect(observer.read(video, track)).toBeNull();
    observer.dispose();
  });

  it('rechecks track presence against the current same-video snapshot before serving a captured body', async () => {
    const { page, observer, setTracks } = harness(async (input) => response(String(input)), () => true);
    await page.fetch(timedtext);
    await vi.waitFor(() => expect(observer.read(video, track)).not.toBeNull());
    setTracks([{ ...track, id: 'other' }]);
    expect(observer.read(video, track)).toBeNull();
    observer.dispose();
  });

  it.each([
    ['', 200, 'EMPTY_RESPONSE'], [json3, 206, 'RESPONSE_REJECTED'],
    [JSON.stringify({ events: [{ tStartMs: 0, segs: [{ utf8: 'Partial' }] }], continuation: 'next' }), 200, 'UNSUPPORTED_BODY'],
  ] as const)('does not accept empty, partial or paged responses (status %s / %s)', async (body, status, result) => {
    const { page, observer } = harness(async (url) => response(String(url), body, status), () => true);
    await page.fetch(timedtext);
    await vi.waitFor(() => expect(observer.diagnostics()).toContainEqual(expect.objectContaining({ result, status })));
    expect(observer.read(video, track)).toBeNull();
    observer.dispose();
  });

  it('keeps a captured XHR as one parsed response and preserves Unicode beyond the BMP', () => {
    const { observer, FakeXHR } = harness(vi.fn(), () => true);
    const xhr = new FakeXHR();
    xhr.open('GET', base);
    xhr.send();
    expect(observer.read(video, track)?.segments).toEqual([{ startMs: 0, text: '\u{20BB7}' }]);
    observer.dispose();
  });

  it('does not resurrect a capture or an old XHR after A -> B -> A or read Resource Timing', async () => {
    const { page, observer, FakeXHR, navigate } = harness(async (url) => response(String(url)), () => true);
    await page.fetch(timedtext);
    await vi.waitFor(() => expect(observer.read(video, track)).not.toBeNull());
    const old = new FakeXHR();
    old.open('GET', base);
    observer.startNavigation();
    navigate(otherVideo);
    observer.finishNavigation();
    observer.startNavigation();
    navigate(video);
    observer.finishNavigation();
    old.send();
    expect(observer.read(video, track)).toBeNull();
    expect(observer.diagnostics()).toEqual([]);
    observer.dispose();
  });

  it('drops a response that finishes streaming during SPA navigation without interrupting the player body', async () => {
    let stream!: ReadableStreamDefaultController<Uint8Array>;
    const body = new ReadableStream<Uint8Array>({ start: (controller) => { stream = controller; } });
    const { page, observer, navigate } = harness(async (url) => response(String(url), body), () => true);
    const original = await page.fetch(timedtext);
    stream.enqueue(new TextEncoder().encode(json3.slice(0, 10)));
    observer.startNavigation();
    navigate(otherVideo);
    observer.finishNavigation();
    navigate(video);
    observer.finishNavigation();
    stream.enqueue(new TextEncoder().encode(json3.slice(10)));
    stream.close();
    expect(await original.text()).toBe(json3);
    expect(observer.read(video, track)).toBeNull();
    observer.dispose();
  });

  it('applies the byte cap while reading an actual stream without a content-length header', async () => {
    const data = new Uint8Array(MAX_RESPONSE_BYTES + 1).fill(42);
    const stream = new ReadableStream<Uint8Array>({ start: (controller) => {
      controller.enqueue(data);
      controller.close();
    } });
    const { page, observer } = harness(async (url) => response(String(url), stream), () => true);
    const original = await page.fetch(timedtext);
    expect((await original.arrayBuffer()).byteLength).toBe(data.byteLength);
    await vi.waitFor(() => expect(observer.diagnostics()).toContainEqual(expect.objectContaining({ result: 'RESPONSE_TOO_LARGE' })));
    expect(observer.read(video, track)).toBeNull();
    observer.dispose();
  });
});
