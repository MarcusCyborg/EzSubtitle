import { describe, expect, it } from 'vitest';
import {
  captionTrackDisplayLabel,
  captionTracksFromPlayerResponse,
  isTrustedCaptionUrl,
  selectDefaultTrack,
} from '../../src/lib/youtube/caption-tracks';

const response = {
  captions: { playerCaptionsTracklistRenderer: { captionTracks: [
    { baseUrl: 'https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=fr', languageCode: 'fr', vssId: '.fr', name: { simpleText: 'Français' } },
    { baseUrl: 'https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=en&kind=asr', languageCode: 'en', vssId: 'a.en', kind: 'asr', name: { simpleText: 'English (auto)' } },
    { baseUrl: 'https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=en', languageCode: 'en', vssId: '.en', name: { simpleText: 'English' } },
  ] } },
};

describe('caption track extraction', () => {
  it('keeps languages and chooses manual English before automatic English', () => {
    const tracks = captionTracksFromPlayerResponse(response);
    expect(tracks).toHaveLength(3);
    expect(selectDefaultTrack(tracks)?.label).toBe('English');
    expect(tracks.find((track) => track.label === 'English (auto)')?.isAutoGenerated).toBe(true);
  });

  it('only trusts YouTube timedtext HTTPS endpoints', () => {
    expect(isTrustedCaptionUrl('https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ')).toBe(true);
    expect(isTrustedCaptionUrl('https://evil.example/api/timedtext')).toBe(false);
    expect(isTrustedCaptionUrl('http://www.youtube.com/api/timedtext')).toBe(false);
  });

  it('does not append a second automatic-caption suffix', () => {
    expect(captionTrackDisplayLabel({ label: 'Tiếng Việt (được tạo tự động)', isAutoGenerated: true }))
      .toBe('Tiếng Việt (được tạo tự động)');
    expect(captionTrackDisplayLabel({ label: 'English', isAutoGenerated: true })).toBe('English (tự động)');
  });
});
