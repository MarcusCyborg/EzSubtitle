import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { YoutubeTranscriptPanel } from '../../src/lib/youtube/youtube-panel';
import type { RuntimeResponse, TranscriptResult, VideoContextResponse } from '../../src/types/messages';
import type { CaptionTrack, VideoContext } from '../../src/types/transcript';

const english: CaptionTrack = {
  id: '.en', languageCode: 'en', label: 'English',
  baseUrl: 'https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=en', isAutoGenerated: false,
};
const vietnamese: CaptionTrack = {
  id: '.vi', languageCode: 'vi', label: 'Tiếng Việt',
  baseUrl: 'https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=vi', isAutoGenerated: false,
};

const context = (title: string, tracks = [english, vietnamese]): VideoContext => ({
  videoId: 'dQw4w9WgXcQ', title, url: 'https://www.youtube.com/watch?v=dQw4w9WgXcQ', tracks,
});
const transcript = (text: string): RuntimeResponse<TranscriptResult> => ({
  ok: true,
  data: { segments: [{ startMs: 1_000, text }], text: `[00:00:01] ${text}` },
});
const multiTranscript = (): RuntimeResponse<TranscriptResult> => ({
  ok: true,
  data: {
    segments: [
      { startMs: 1_000, text: 'First' },
      { startMs: 7_000, text: 'sentence.' },
      { startMs: 14_000, text: 'Next block.' },
    ],
    text: '[00:00:01] First\n[00:00:07] sentence.\n[00:00:14] Next block.',
  },
});
const successContext = (value: VideoContext): VideoContextResponse => ({ ok: true, data: value });

let panel: YoutubeTranscriptPanel | null = null;
const runtimeSendMessage = vi.fn(async () => ({ ok: true, data: { tabId: 99 } }));

async function settle(): Promise<void> {
  await Promise.resolve();
  await Promise.resolve();
  await new Promise((resolve) => window.setTimeout(resolve, 0));
}

function panelRoot(): ShadowRoot {
  const host = document.getElementById('ezsubtitle-youtube-panel-host');
  if (!host?.shadowRoot) throw new Error('Panel host was not mounted.');
  return host.shadowRoot;
}

beforeEach(() => {
  runtimeSendMessage.mockClear();
  document.body.innerHTML = '<ytd-watch-flexy><div id="secondary"><div id="secondary-inner"></div></div></ytd-watch-flexy><video class="html5-main-video"></video>';
  const video = document.querySelector('video')!;
  Object.defineProperty(video, 'readyState', { configurable: true, value: HTMLMediaElement.HAVE_METADATA });
  Object.defineProperty(window, 'requestAnimationFrame', { configurable: true, value: (callback: FrameRequestCallback) => {
    callback(0);
    return 1;
  } });
  Object.defineProperty(globalThis, 'chrome', {
    configurable: true,
    value: {
      storage: { local: { get: vi.fn(async () => ({ youtubePanelExpanded: true })), set: vi.fn(async () => undefined) } },
      runtime: {
        getURL: (path: string) => `chrome-extension://fixture/${path}`,
        sendMessage: runtimeSendMessage,
      },
    },
  });
  Object.defineProperty(navigator, 'clipboard', {
    configurable: true,
    value: { writeText: vi.fn(async () => undefined) },
  });
});

afterEach(() => {
  panel?.destroy();
  panel = null;
  vi.restoreAllMocks();
});

describe('YouTube panel lifecycle', () => {
  it('starts collapsed by default and loads only after the user expands it', async () => {
    vi.mocked(chrome.storage.local.get as (key: string) => Promise<Record<string, unknown>>).mockResolvedValue({});
    const loadContext = vi.fn(async () => successContext(context('Fixture')));
    panel = new YoutubeTranscriptPanel({
      loadContext,
      loadTranscript: async () => transcript('Hello'),
    });

    panel.start();
    await settle();

    const header = panelRoot().querySelector<HTMLButtonElement>('.header')!;
    expect(header.getAttribute('aria-expanded')).toBe('false');
    expect(header.title).toBe('Mở transcript');
    expect(panelRoot().querySelector('.body')).toBeNull();
    expect(loadContext).not.toHaveBeenCalled();

    header.click();
    await settle();

    expect(panelRoot().querySelector('.header')?.getAttribute('aria-expanded')).toBe('true');
    expect(loadContext).toHaveBeenCalledOnce();
  });

  it('does not rebuild transcript rows for unrelated DOM mutations', async () => {
    panel = new YoutubeTranscriptPanel({
      loadContext: async () => successContext(context('Fixture')),
      loadTranscript: async () => transcript('Hello'),
    });
    panel.start();
    await settle();
    const row = panelRoot().querySelector('[data-segment-index="0"]');

    document.body.append(document.createElement('aside'));
    await settle();

    expect(panelRoot().querySelector('[data-segment-index="0"]')).toBe(row);
  });

  it('remounts once when YouTube replaces the sidebar and never duplicates the host', async () => {
    panel = new YoutubeTranscriptPanel({
      loadContext: async () => successContext(context('Fixture')),
      loadTranscript: async () => transcript('Hello'),
    });
    panel.start();
    await settle();
    const host = document.getElementById('ezsubtitle-youtube-panel-host');
    const replacement = document.createElement('div');
    replacement.id = 'secondary-inner';
    document.querySelector('#secondary-inner')?.replaceWith(replacement);
    await settle();

    expect(replacement.firstElementChild).toBe(host);
    expect(document.querySelectorAll('#ezsubtitle-youtube-panel-host')).toHaveLength(1);
  });

  it('clears old SPA state and ignores a transcript response from the previous navigation', async () => {
    let resolveOld: ((value: RuntimeResponse<TranscriptResult>) => void) | undefined;
    let currentContext = context('Video A');
    const loadTranscript = vi.fn((videoId: string) => {
      if (currentContext.title === 'Video A') {
        return new Promise<RuntimeResponse<TranscriptResult>>((resolve) => { resolveOld = resolve; });
      }
      return Promise.resolve(transcript(`Video B ${videoId}`));
    });
    panel = new YoutubeTranscriptPanel({
      loadContext: async () => successContext(currentContext),
      loadTranscript,
    });
    panel.start();
    await settle();
    currentContext = context('Video B');
    window.dispatchEvent(new Event('yt-navigate-finish'));
    expect(panelRoot().querySelector('.transcript')).toBeNull();
    await settle();
    resolveOld?.(transcript('Old response'));
    await settle();

    expect(panelRoot().textContent).toContain('Video B dQw4w9WgXcQ');
    expect(panelRoot().textContent).not.toContain('Old response');
  });

  it('keeps the newest track when language requests finish out of order', async () => {
    let resolveEnglish: ((value: RuntimeResponse<TranscriptResult>) => void) | undefined;
    panel = new YoutubeTranscriptPanel({
      loadContext: async () => successContext(context('Fixture')),
      loadTranscript: async (_videoId, track) => track.languageCode === 'en'
        ? new Promise<RuntimeResponse<TranscriptResult>>((resolve) => { resolveEnglish = resolve; })
        : transcript('Vietnamese response'),
    });
    panel.start();
    await settle();
    const select = panelRoot().querySelector<HTMLSelectElement>('select')!;
    select.value = '.vi';
    select.dispatchEvent(new Event('change'));
    await settle();
    resolveEnglish?.(transcript('Stale English response'));
    await settle();

    expect(panelRoot().textContent).toContain('Vietnamese response');
    expect(panelRoot().textContent).not.toContain('Stale English response');
  });

  it('jump scrolls only the transcript while clicking a row seeks the video', async () => {
    panel = new YoutubeTranscriptPanel({
      loadContext: async () => successContext(context('Fixture', [english])),
      loadTranscript: async () => transcript('Hello'),
    });
    panel.start();
    await settle();
    const root = panelRoot();
    const video = document.querySelector<HTMLVideoElement>('video')!;
    video.currentTime = 1;
    const scroller = root.querySelector<HTMLElement>('.transcript')!;
    const scrollTo = vi.fn();
    Object.defineProperty(scroller, 'scrollTo', { configurable: true, value: scrollTo });

    root.querySelector<HTMLButtonElement>('[title="Đi tới thời điểm hiện tại"]')?.click();
    expect(video.currentTime).toBe(1);
    expect(scrollTo).toHaveBeenCalledOnce();

    video.currentTime = 0;
    root.querySelector<HTMLButtonElement>('[data-segment-index="0"]')?.click();
    expect(video.currentTime).toBe(1);
  });

  it('highlights and follows the active line until the user turns following off', async () => {
    panel = new YoutubeTranscriptPanel({
      loadContext: async () => successContext(context('Fixture', [english])),
      loadTranscript: async () => multiTranscript(),
    });
    panel.start();
    await settle();
    const root = panelRoot();
    const video = document.querySelector<HTMLVideoElement>('video')!;
    const scroller = root.querySelector<HTMLElement>('.transcript')!;
    const scrollTo = vi.fn();
    Object.defineProperty(scroller, 'scrollTo', { configurable: true, value: scrollTo });

    video.currentTime = 7;
    video.dispatchEvent(new Event('timeupdate'));
    expect(root.querySelector('[data-segment-index="1"]')?.classList.contains('segment--active')).toBe(true);
    expect(scrollTo).toHaveBeenCalledOnce();

    const follow = root.querySelector<HTMLButtonElement>('[data-action="follow-playback"]')!;
    expect(follow.getAttribute('aria-pressed')).toBe('true');
    follow.click();
    expect(follow.title).toBe('Bật tự theo dõi');
    video.currentTime = 14;
    video.dispatchEvent(new Event('timeupdate'));
    expect(root.querySelector('[data-segment-index="2"]')?.classList.contains('segment--active')).toBe(true);
    expect(scrollTo).toHaveBeenCalledOnce();

    follow.click();
    expect(follow.title).toBe('Tắt tự theo dõi');
    expect(follow.getAttribute('aria-pressed')).toBe('true');
    expect(scrollTo).toHaveBeenCalledTimes(2);
  });

  it('keeps detailed rows and seek offsets while switching export mode without reloading', async () => {
    const loadTranscript = vi.fn(async () => multiTranscript());
    panel = new YoutubeTranscriptPanel({
      loadContext: async () => successContext(context('Fixture', [english])),
      loadTranscript,
    });
    panel.start();
    await settle();
    const root = panelRoot();
    const firstRow = root.querySelector<HTMLButtonElement>('[data-segment-index="0"]')!;

    root.querySelector<HTMLButtonElement>('[title="Sao chép transcript"]')?.click();
    await settle();
    expect(navigator.clipboard.writeText).toHaveBeenLastCalledWith('(00:01) First sentence.\n\n(00:14) Next block.');

    const outputSelect = root.querySelector<HTMLSelectElement>('[aria-label="Định dạng xuất transcript"]')!;
    const currentFirstRow = root.querySelector('[data-segment-index="0"]');
    outputSelect.value = 'detailed';
    outputSelect.dispatchEvent(new Event('change'));
    expect(root.querySelector('[data-segment-index="0"]')).toBe(currentFirstRow);
    root.querySelector<HTMLButtonElement>('[title="Sao chép transcript"]')?.click();
    await settle();

    expect(loadTranscript).toHaveBeenCalledTimes(1);
    expect(loadTranscript).toHaveBeenCalledWith('dQw4w9WgXcQ', english, 1);
    expect(root.querySelectorAll('[data-segment-index]')).toHaveLength(3);
    expect(navigator.clipboard.writeText).toHaveBeenLastCalledWith('[00:00:01] First\n[00:00:07] sentence.\n[00:00:14] Next block.');

    const video = document.querySelector<HTMLVideoElement>('video')!;
    firstRow.click();
    expect(video.currentTime).toBe(1);
  });

  it('searches, highlights, navigates, and seeks from the keyboard', async () => {
    panel = new YoutubeTranscriptPanel({
      loadContext: async () => successContext(context('Fixture', [english])),
      loadTranscript: async () => multiTranscript(),
    });
    panel.start();
    await settle();
    const root = panelRoot();
    const input = root.querySelector<HTMLInputElement>('[aria-label="Tìm trong transcript"]')!;
    input.value = 'sentence';
    input.dispatchEvent(new Event('input'));

    expect(root.querySelector('[data-search-count]')?.textContent).toBe('1 kq');
    expect(root.querySelectorAll('mark')).toHaveLength(1);
    expect(root.querySelector('mark')?.textContent).toBe('sentence');

    input.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter' }));
    expect(document.querySelector<HTMLVideoElement>('video')?.currentTime).toBe(7);
    expect(root.querySelector('[data-search-count]')?.textContent).toBe('1/1');
    expect(root.querySelector('[data-segment-index="1"]')?.classList).toContain('segment--search-current');
  });

  it('places the summary action before the dropdown and prepares a ChatGPT draft without sending it', async () => {
    panel = new YoutubeTranscriptPanel({
      loadContext: async () => successContext(context('Fixture', [english])),
      loadTranscript: async () => multiTranscript(),
    });
    panel.start();
    await settle();
    const root = panelRoot();
    const header = root.querySelector('.header-row')!;
    const summary = root.querySelector<HTMLButtonElement>('.summary-button')!;
    const dropdown = root.querySelector<HTMLButtonElement>('.header-chevron')!;

    expect(Array.from(header.children).indexOf(summary)).toBeLessThan(Array.from(header.children).indexOf(dropdown));
    summary.click();
    await settle();

    expect(runtimeSendMessage).toHaveBeenCalledOnce();
    expect(runtimeSendMessage).toHaveBeenCalledWith({
      type: 'PREPARE_CHATGPT_DRAFT',
      transcript: '(00:01) First sentence.\n\n(00:14) Next block.',
    });
  });

  it('uses identical text for clipboard and download in the same mode', async () => {
    let downloadedText = '';
    vi.stubGlobal('Blob', class {
      constructor(parts: BlobPart[]) {
        downloadedText = parts.map(String).join('');
      }
    });
    vi.spyOn(URL, 'createObjectURL').mockReturnValue('blob:fixture');
    vi.spyOn(URL, 'revokeObjectURL').mockImplementation(() => undefined);
    vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => undefined);
    panel = new YoutubeTranscriptPanel({
      loadContext: async () => successContext(context('Fixture', [english])),
      loadTranscript: async () => multiTranscript(),
    });
    panel.start();
    await settle();
    const root = panelRoot();
    root.querySelector<HTMLButtonElement>('[title="Sao chép transcript"]')?.click();
    root.querySelector<HTMLButtonElement>('[title="Tải transcript .txt"]')?.click();
    await settle();

    const clipboardText = vi.mocked(navigator.clipboard.writeText).mock.calls.at(-1)?.[0];
    expect(downloadedText).toBe(clipboardText);
  });
});
