import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import App from '../../entrypoints/popup/App';

let root: Root | null = null;
let container: HTMLDivElement | null = null;
const runtimeSendMessage = vi.fn();

async function settle(): Promise<void> {
  await act(async () => {
    await Promise.resolve();
    await Promise.resolve();
    await new Promise((resolve) => window.setTimeout(resolve, 0));
  });
}

beforeEach(() => {
  Object.assign(globalThis, { IS_REACT_ACT_ENVIRONMENT: true });
  runtimeSendMessage.mockReset();
  runtimeSendMessage.mockImplementation(async (message: { type?: string }) => {
    if (message.type === 'FETCH_TRANSCRIPT') {
      return {
        ok: true,
        data: {
          segments: [
            { startMs: 6_000, text: 'First' },
            { startMs: 12_000, text: 'sentence.' },
            { startMs: 20_000, text: 'Next block.' },
          ],
          text: '[00:00:06] First\n[00:00:12] sentence.\n[00:00:20] Next block.',
        },
      };
    }
    if (message.type === 'PREPARE_CHATGPT_DRAFT') return { ok: true, data: { tabId: 9 } };
    return { ok: true, data: null };
  });
  Object.defineProperty(globalThis, 'chrome', {
    configurable: true,
    value: {
      runtime: {
        lastError: undefined,
        sendMessage: runtimeSendMessage,
        onMessage: { addListener: vi.fn(), removeListener: vi.fn() },
      },
      storage: { local: { get: vi.fn(async () => ({})), set: vi.fn(async () => undefined) } },
      tabs: {
        query: vi.fn(async () => [{ id: 7, url: 'https://www.youtube.com/watch?v=dQw4w9WgXcQ' }]),
        sendMessage: vi.fn(async () => ({
          ok: true,
          data: {
            videoId: 'dQw4w9WgXcQ',
            title: 'Fixture video',
            url: 'https://www.youtube.com/watch?v=dQw4w9WgXcQ',
            tracks: [{
              id: '.en', languageCode: 'en', label: 'English',
              baseUrl: 'https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=en', isAutoGenerated: false,
            }],
          },
        })),
      },
    },
  });
  container = document.createElement('div');
  document.body.replaceChildren(container);
  root = createRoot(container);
});

afterEach(async () => {
  if (root) await act(async () => root?.unmount());
  root = null;
  container = null;
  vi.restoreAllMocks();
});

describe('popup output modes', () => {
  it('uses readable output for preview and ChatGPT by default without refetching on mode change', async () => {
    await act(async () => root?.render(<App />));
    await settle();

    const preview = document.querySelector<HTMLTextAreaElement>('[aria-label="Nội dung phụ đề"]')!;
    expect(preview.value).toBe('(00:06) First sentence.\n\n(00:20) Next block.');
    expect(runtimeSendMessage).toHaveBeenCalledWith(expect.objectContaining({
      type: 'FETCH_TRANSCRIPT',
      videoId: 'dQw4w9WgXcQ',
      trackCount: 1,
    }));
    const chatButton = [...document.querySelectorAll<HTMLButtonElement>('button')]
      .find((button) => button.textContent === 'Tóm tắt bằng ChatGPT')!;
    await act(async () => chatButton.click());
    expect(runtimeSendMessage).toHaveBeenCalledWith({
      type: 'PREPARE_CHATGPT_DRAFT',
      transcript: '(00:06) First sentence.\n\n(00:20) Next block.',
    });

    const fetchCount = runtimeSendMessage.mock.calls.filter(([message]) => message.type === 'FETCH_TRANSCRIPT').length;
    const outputSelect = document.querySelector<HTMLSelectElement>('.output-selector select')!;
    await act(async () => {
      outputSelect.value = 'detailed';
      outputSelect.dispatchEvent(new Event('change', { bubbles: true }));
    });

    expect(preview.value).toBe('[00:00:06] First\n[00:00:12] sentence.\n[00:00:20] Next block.');
    expect(runtimeSendMessage.mock.calls.filter(([message]) => message.type === 'FETCH_TRANSCRIPT')).toHaveLength(fetchCount);
  });
});
