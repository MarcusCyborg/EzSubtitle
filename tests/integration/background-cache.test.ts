import { beforeAll, beforeEach, describe, expect, it, vi } from 'vitest';
import type { CaptionTrack } from '../../src/types/transcript';
import { transcriptResult } from '../../src/lib/transcript/provenance';

const videoId = 'dQw4w9WgXcQ';
const sender = { tab: { id: 7 } as chrome.tabs.Tab };
const storage: Record<string, unknown> = {};
const json3 = (text: string) => new Response(JSON.stringify({ events: [{ tStartMs: 1_000, segs: [{ utf8: text }] }] }));

const track: CaptionTrack = {
  id: '.en', languageCode: 'en', label: 'English',
  baseUrl: 'https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=en', isAutoGenerated: false,
};

let handleFetchTranscript: typeof import('../../entrypoints/background')['handleFetchTranscript'];
const storageSet = vi.fn(async (values: Record<string, unknown>) => Object.assign(storage, values));
const tabsGet = vi.fn();
const tabsSendMessage = vi.fn(async (): Promise<unknown> => undefined);

beforeAll(async () => {
  vi.stubGlobal('defineBackground', (value: unknown) => value);
  ({ handleFetchTranscript } = await import('../../entrypoints/background'));
});

beforeEach(() => {
  for (const key of Object.keys(storage)) delete storage[key];
  storageSet.mockClear();
  tabsGet.mockReset();
  tabsSendMessage.mockReset();
  Object.defineProperty(globalThis, 'chrome', {
    configurable: true,
    value: {
      storage: { session: { get: vi.fn(async (key: string) => ({ [key]: storage[key] })), set: storageSet } },
      tabs: { get: tabsGet, sendMessage: tabsSendMessage },
    },
  });
});

describe('background transcript cache ownership', () => {
  it('rejects a caption URL that belongs to video A when requested as video B', async () => {
    const wrongTrack = { ...track, baseUrl: 'https://www.youtube.com/api/timedtext?v=9bZkp7q19f0&lang=en' };
    const response = await handleFetchTranscript('dQw4w9WgXcQ', wrongTrack, { tab: { id: 7 } as chrome.tabs.Tab });

    expect(response).toMatchObject({ ok: false, error: { code: 'INVALID_CAPTION_URL' } });
    expect(storageSet).not.toHaveBeenCalled();
  });

  it('does not cache a completed response after the source tab navigates away', async () => {
    tabsGet
      .mockResolvedValueOnce({ url: 'https://www.youtube.com/watch?v=dQw4w9WgXcQ' })
      .mockResolvedValueOnce({ url: 'https://www.youtube.com/watch?v=9bZkp7q19f0' });
    vi.stubGlobal('fetch', vi.fn(async () => new Response(JSON.stringify({
      events: [{ tStartMs: 1_000, segs: [{ utf8: 'Video A transcript' }] }],
    }))));

    const response = await handleFetchTranscript('dQw4w9WgXcQ', track, { tab: { id: 7 } as chrome.tabs.Tab });

    expect(response).toMatchObject({ ok: false, error: { code: 'STALE_VIDEO' } });
    expect(storageSet).not.toHaveBeenCalled();
  });

  it('does not cache a native transcript response rejected as unstable', async () => {
    tabsGet.mockResolvedValue({ url: 'https://www.youtube.com/watch?v=dQw4w9WgXcQ' });
    vi.stubGlobal('fetch', vi.fn(async () => new Response('', { status: 404 })));
    tabsSendMessage.mockResolvedValue({
      ok: false,
      error: { code: 'NATIVE_TRANSCRIPT_UNSTABLE', message: 'Mixed DOM was discarded.' },
    });

    const response = await handleFetchTranscript('dQw4w9WgXcQ', track, { tab: { id: 7 } as chrome.tabs.Tab });

    expect(response).toMatchObject({ ok: false, error: { code: 'NATIVE_TRANSCRIPT_UNSTABLE' } });
    expect(storageSet).not.toHaveBeenCalled();
  });

  it('forwards the authoritative track count to the page fallback', async () => {
    tabsGet.mockResolvedValue({ url: 'https://www.youtube.com/watch?v=dQw4w9WgXcQ' });
    vi.stubGlobal('fetch', vi.fn(async () => new Response('', { status: 404 })));
    tabsSendMessage.mockResolvedValue({
      ok: true,
      data: transcriptResult([{ startMs: 1_000, text: 'Native transcript' }], videoId, track, 'native-dom'),
    });

    await handleFetchTranscript('dQw4w9WgXcQ', track, { tab: { id: 7 } as chrome.tabs.Tab }, undefined, 1);

    expect(tabsSendMessage).toHaveBeenCalledWith(7, {
      type: 'FETCH_PAGE_TRANSCRIPT', videoId: 'dQw4w9WgXcQ', track, trackCount: 1,
    });
  });

  it('labels a fallback and retries timedtext on the next request instead of caching native text', async () => {
    tabsGet.mockResolvedValue({ url: `https://www.youtube.com/watch?v=${videoId}` });
    const fetch = vi.fn()
      .mockImplementationOnce(async () => new Response('', { status: 410 }))
      .mockImplementationOnce(async () => json3('Timedtext became available'))
      .mockImplementationOnce(async () => json3('Fresh timedtext'));
    vi.stubGlobal('fetch', fetch);
    tabsSendMessage.mockResolvedValue({ ok: true, data: transcriptResult(
      [{ startMs: 1_000, text: 'Native fallback' }], videoId, track, 'native-dom', ['EMPTY_RESPONSE'],
    ) });

    await expect(handleFetchTranscript(videoId, track, sender)).resolves.toMatchObject({
      ok: true, data: { provenance: { source: 'native-dom', cacheHit: false, fallbackErrors: ['PLAYER_CC_UNAVAILABLE', 'CAPTION_UNAVAILABLE', 'EMPTY_RESPONSE'] } },
    });
    expect(storageSet).not.toHaveBeenCalled();
    await expect(handleFetchTranscript(videoId, track, sender)).resolves.toMatchObject({
      ok: true, data: { provenance: { source: 'background-timedtext', cacheHit: false } },
    });
    await expect(handleFetchTranscript(videoId, track, sender)).resolves.toMatchObject({
      ok: true, data: { provenance: { source: 'background-timedtext', cacheHit: true } },
    });
    await expect(handleFetchTranscript(videoId, track, sender, undefined, undefined, true)).resolves.toMatchObject({
      ok: true, data: { segments: [{ startMs: 1_000, text: 'Fresh timedtext' }], provenance: { cacheHit: false } },
    });
    expect(fetch).toHaveBeenCalledTimes(3);
  });

  it('uses captured player CC before successful metadata, upgrades a metadata cache hit, and keeps CC out of storage', async () => {
    tabsGet.mockResolvedValue({ url: `https://www.youtube.com/watch?v=${videoId}` });
    const transport = vi.fn(async () => json3('Metadata transcript'));
    vi.stubGlobal('fetch', transport);
    const player = transcriptResult([{ startMs: 1_100, text: 'Player transcript' }], videoId, track, 'player-timedtext');
    tabsSendMessage.mockResolvedValueOnce({ ok: true, data: player });
    await expect(handleFetchTranscript(videoId, track, sender)).resolves.toEqual({ ok: true, data: player });
    expect(transport).not.toHaveBeenCalled();

    await expect(handleFetchTranscript(videoId, track, sender)).resolves.toMatchObject({
      ok: true, data: { provenance: { source: 'background-timedtext', cacheHit: false } },
    });
    tabsSendMessage.mockResolvedValue({ ok: true, data: player });
    await expect(handleFetchTranscript(videoId, track, sender)).resolves.toEqual({ ok: true, data: player });
    await expect(handleFetchTranscript(videoId, track, sender, undefined, undefined, true)).resolves.toEqual({ ok: true, data: player });
    expect(transport).toHaveBeenCalledTimes(1);
    expect(storageSet).toHaveBeenCalledTimes(1);
    expect(JSON.stringify(storage)).not.toContain('Player transcript');
  });

  it('rejects stale probes before going to cache or metadata', async () => {
    tabsGet.mockResolvedValue({ url: `https://www.youtube.com/watch?v=${videoId}` });
    const transport = vi.fn(async () => json3('Metadata transcript'));
    vi.stubGlobal('fetch', transport);
    tabsSendMessage.mockResolvedValue({ ok: false, error: { code: 'STALE_VIDEO', message: 'Navigation' } });
    await expect(handleFetchTranscript(videoId, track, sender)).resolves.toMatchObject({ ok: false, error: { code: 'STALE_VIDEO' } });
    expect(storageSet).not.toHaveBeenCalled();
    expect(transport).not.toHaveBeenCalled();
  });

  it.each(['lang=vi', 'lang=en&kind=asr', 'lang=en&lang=vi'])('rejects metadata when the selected track contradicts %s', async (query) => {
    await expect(handleFetchTranscript(videoId, {
      ...track, baseUrl: `https://www.youtube.com/api/timedtext?v=${videoId}&${query}`,
    }, sender)).resolves.toMatchObject({ ok: false, error: { code: 'INVALID_CAPTION_URL' } });
    expect(tabsGet).not.toHaveBeenCalled();
  });

  it('rejects the page fallback for another translation', async () => {
    tabsGet.mockResolvedValue({ url: `https://www.youtube.com/watch?v=${videoId}` });
    vi.stubGlobal('fetch', vi.fn(async () => new Response('')));
    tabsSendMessage.mockResolvedValue({ ok: true, data: transcriptResult(
      [{ startMs: 0, text: 'Original' }], videoId, track, 'native-dom',
    ) });
    await expect(handleFetchTranscript(videoId, { ...track, baseUrl: track.baseUrl + '&tlang=vi' }, sender))
      .resolves.toMatchObject({ ok: false });
    expect(storageSet).not.toHaveBeenCalled();
  });
});
