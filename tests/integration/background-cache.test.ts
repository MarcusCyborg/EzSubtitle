import { beforeAll, beforeEach, describe, expect, it, vi } from 'vitest';
import type { CaptionTrack } from '../../src/types/transcript';

const track: CaptionTrack = {
  id: '.en', languageCode: 'en', label: 'English',
  baseUrl: 'https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=en', isAutoGenerated: false,
};

let handleFetchTranscript: typeof import('../../entrypoints/background')['handleFetchTranscript'];
const storageSet = vi.fn(async () => undefined);
const tabsGet = vi.fn();
const tabsSendMessage = vi.fn(async (): Promise<unknown> => undefined);

beforeAll(async () => {
  vi.stubGlobal('defineBackground', (value: unknown) => value);
  ({ handleFetchTranscript } = await import('../../entrypoints/background'));
});

beforeEach(() => {
  storageSet.mockClear();
  tabsGet.mockReset();
  Object.defineProperty(globalThis, 'chrome', {
    configurable: true,
    value: {
      storage: { session: { get: vi.fn(async () => ({})), set: storageSet } },
      tabs: { get: tabsGet, sendMessage: tabsSendMessage },
    },
  });
});

describe('background transcript cache ownership', () => {
  it('rejects a caption URL that belongs to video A when requested as video B', async () => {
    const wrongTrack = { ...track, baseUrl: 'https://www.youtube.com/api/timedtext?v=9bZkp7q19f0&lang=en' };
    const response = await handleFetchTranscript('dQw4w9WgXcQ', wrongTrack, { tab: { id: 7 } as chrome.tabs.Tab });

    expect(response).toMatchObject({ ok: false, error: { code: 'INVALID_CAPTION_URL' } });
    expect(storageSet).not.toHaveBeenCalled();
  });

  it('does not cache a completed response after the source tab navigates away', async () => {
    tabsGet
      .mockResolvedValueOnce({ url: 'https://www.youtube.com/watch?v=dQw4w9WgXcQ' })
      .mockResolvedValueOnce({ url: 'https://www.youtube.com/watch?v=9bZkp7q19f0' });
    vi.stubGlobal('fetch', vi.fn(async () => new Response(JSON.stringify({
      events: [{ tStartMs: 1_000, segs: [{ utf8: 'Video A transcript' }] }],
    }))));

    const response = await handleFetchTranscript('dQw4w9WgXcQ', track, { tab: { id: 7 } as chrome.tabs.Tab });

    expect(response).toMatchObject({ ok: false, error: { code: 'STALE_VIDEO' } });
    expect(storageSet).not.toHaveBeenCalled();
  });

  it('does not cache a native transcript response rejected as unstable', async () => {
    tabsGet.mockResolvedValue({ url: 'https://www.youtube.com/watch?v=dQw4w9WgXcQ' });
    vi.stubGlobal('fetch', vi.fn(async () => new Response('', { status: 404 })));
    tabsSendMessage.mockResolvedValue({
      ok: false,
      error: { code: 'NATIVE_TRANSCRIPT_UNSTABLE', message: 'Mixed DOM was discarded.' },
    });

    const response = await handleFetchTranscript('dQw4w9WgXcQ', track, { tab: { id: 7 } as chrome.tabs.Tab });

    expect(response).toMatchObject({ ok: false, error: { code: 'NATIVE_TRANSCRIPT_UNSTABLE' } });
    expect(storageSet).not.toHaveBeenCalled();
  });

  it('forwards the authoritative track count to the page fallback', async () => {
    tabsGet.mockResolvedValue({ url: 'https://www.youtube.com/watch?v=dQw4w9WgXcQ' });
    vi.stubGlobal('fetch', vi.fn(async () => new Response('', { status: 404 })));
    tabsSendMessage.mockResolvedValue({
      ok: true,
      data: { segments: [{ startMs: 1_000, text: 'Native transcript' }], text: '(00:01) Native transcript' },
    });

    await handleFetchTranscript('dQw4w9WgXcQ', track, { tab: { id: 7 } as chrome.tabs.Tab }, undefined, 1);

    expect(tabsSendMessage).toHaveBeenCalledWith(7, {
      type: 'FETCH_PAGE_TRANSCRIPT', videoId: 'dQw4w9WgXcQ', track, trackCount: 1,
    });
  });
});
