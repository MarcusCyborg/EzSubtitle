import { beforeAll, beforeEach, describe, expect, it, vi } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

type ContentDefinition = { main: () => void };
let definition: ContentDefinition;
let onRuntimeMessage: ((message: unknown, sender: unknown, sendResponse: (value: unknown) => void) => boolean | undefined) | undefined;
let snapshot: unknown;
let getVideoContext: typeof import('../../entrypoints/content')['getVideoContext'];
let fetchPageTranscript: typeof import('../../entrypoints/content')['fetchPageTranscript'];
const sendMessage = vi.fn();
let snapshotRequests = 0;
let endpointBody = '';
let endpointUnavailable = false;
let nativeErrorCode = 'TRANSCRIPT_ENDPOINT_UNAVAILABLE';
let nativeSegments: Array<{ startMs: number; text: string }> = [];
let nativeIsOnlyTrack = false;

beforeAll(async () => {
  vi.stubGlobal('defineContentScript', (value: ContentDefinition) => {
    definition = value;
    return value;
  });
  vi.stubGlobal('chrome', {
    runtime: {
      onMessage: { addListener: (listener: typeof onRuntimeMessage) => { onRuntimeMessage = listener; } },
      sendMessage,
    },
  });
  window.addEventListener('ezsubtitle:page-request', (event) => {
    const request = (event as CustomEvent<{ requestId: string; action: string; isOnlyTrack?: boolean }>).detail;
    if (request.action === 'FETCH_TIMEDTEXT') {
      window.dispatchEvent(new CustomEvent('ezsubtitle:page-response', {
        detail: { requestId: request.requestId, action: request.action, ok: true, data: { bodies: [], networkFailure: false } },
      }));
      return;
    }
    if (request.action === 'FETCH_TRANSCRIPT_ENDPOINT') {
      window.dispatchEvent(new CustomEvent('ezsubtitle:page-response', {
        detail: endpointUnavailable
          ? { requestId: request.requestId, action: request.action, ok: false, error: { code: 'TRANSCRIPT_ENDPOINT_UNAVAILABLE', message: 'Endpoint unavailable.' } }
          : { requestId: request.requestId, action: request.action, ok: true, data: { body: endpointBody } },
      }));
      return;
    }
    if (request.action === 'FETCH_NATIVE_TRANSCRIPT') {
      nativeIsOnlyTrack = request.isOnlyTrack === true;
      window.dispatchEvent(new CustomEvent('ezsubtitle:page-response', {
        detail: nativeSegments.length
          ? { requestId: request.requestId, action: request.action, ok: true, data: { segments: nativeSegments } }
          : {
            requestId: request.requestId,
            action: request.action,
            ok: false,
            error: { code: nativeErrorCode, message: 'Native transcript unavailable.' },
          },
      }));
      return;
    }
    if (request.action !== 'GET_SNAPSHOT') return;
    snapshotRequests += 1;
    window.dispatchEvent(new CustomEvent('ezsubtitle:page-response', {
      detail: { requestId: request.requestId, action: request.action, ok: true, data: { snapshot } },
    }));
  });
  ({ fetchPageTranscript, getVideoContext } = await import('../../entrypoints/content'));
  definition.main();
});

beforeEach(() => {
  document.body.replaceChildren();
  sendMessage.mockReset();
  snapshotRequests = 0;
  endpointBody = '';
  endpointUnavailable = false;
  nativeErrorCode = 'TRANSCRIPT_ENDPOINT_UNAVAILABLE';
  nativeSegments = [];
  nativeIsOnlyTrack = false;
  snapshot = {
    videoDetails: { videoId: 'dQw4w9WgXcQ', title: 'Fixture video' },
    captions: { playerCaptionsTracklistRenderer: { captionTracks: [
      { baseUrl: 'https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=en', languageCode: 'en', vssId: '.en', name: { simpleText: 'English' } },
      { baseUrl: 'https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=vi', languageCode: 'vi', vssId: '.vi', name: { simpleText: 'Tiếng Việt' } },
    ] } },
  };
  window.history.replaceState({}, '', '/watch?v=dQw4w9WgXcQ');
});

const domTrack = {
  id: '.vi', languageCode: 'vi', label: 'Tiếng Việt',
  baseUrl: 'https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=vi', isAutoGenerated: false,
};

function renderVisibleTranscript(): HTMLElement {
  const panel = document.createElement('ytd-engagement-panel-section-list-renderer');
  panel.setAttribute('target-id', 'engagement-panel-searchable-transcript');
  panel.setAttribute('visibility', 'ENGAGEMENT_PANEL_VISIBILITY_EXPANDED');
  panel.innerHTML = `
    <ytd-transcript-segment-renderer>
      <span class="segment-timestamp">0:07</span><span class="segment-text">Xin chào.</span>
    </ytd-transcript-segment-renderer>
    <ytd-transcript-segment-renderer>
      <span class="segment-timestamp">0:20</span><span class="segment-text">Bài học hôm nay.</span>
    </ytd-transcript-segment-renderer>`;
  document.body.append(panel);
  endpointUnavailable = true;
  return panel;
}

describe('YouTube content bridge mock', () => {
  it('recovers the visible timeline transcript when the MAIN-world bridge cannot open the old panel', async () => {
    document.body.innerHTML = readFileSync(resolve('tests/fixtures/native-timeline.html'), 'utf8');
    endpointUnavailable = true;
    const track = {
      id: 'a.en', languageCode: 'en', label: 'English (auto-generated)',
      baseUrl: 'https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=en&kind=asr', isAutoGenerated: true,
    };
    const response = await fetchPageTranscript('dQw4w9WgXcQ', track, 1);
    expect(response).toMatchObject({ ok: true, data: { segments: [{ startMs: 7_000 }, { startMs: 15_000 }] } });
    if (response.ok) {
      expect(response.data.text).toContain('supply chains,');
      expect(response.data.text).not.toContain('seconds');
    }
  });

  it('recovers formatted text from visible DOM without Polymer data when all bridges fail', async () => {
    renderVisibleTranscript();
    const response = await fetchPageTranscript('dQw4w9WgXcQ', domTrack, 1);
    expect(response).toMatchObject({
      ok: true,
      data: { segments: [{ startMs: 7_000, text: 'Xin chào.' }, { startMs: 20_000, text: 'Bài học hôm nay.' }] },
    });
    if (response.ok) {
      expect(response.data.text).toContain('Xin chào.');
      expect(response.data.text).toContain('Bài học hôm nay.');
    }
  });

  it.each([undefined, 2])('does not guess the visible language with track count %s', async (trackCount) => {
    renderVisibleTranscript();
    await expect(fetchPageTranscript('dQw4w9WgXcQ', domTrack, trackCount)).resolves.toMatchObject({
      ok: false, error: { message: 'Native transcript unavailable.' },
    });
  });

  it.each(['hidden', 'untimed', 'mixed', 'old-video', 'unstable'])('rejects %s native transcript data', async (kind) => {
    const panel = renderVisibleTranscript();
    if (kind === 'hidden') panel.setAttribute('visibility', 'ENGAGEMENT_PANEL_VISIBILITY_HIDDEN');
    if (kind === 'untimed') panel.querySelector('.segment-timestamp')?.remove();
    if (kind === 'mixed') {
      panel.querySelectorAll('ytd-transcript-segment-renderer').forEach((segment, index) => {
        (segment as HTMLElement & { data: unknown }).data = { targetId: `track-${index ? 'en' : 'vi'}:0:1000` };
      });
    }
    if (kind === 'old-video') {
      const watch = document.createElement('ytd-watch-flexy');
      watch.setAttribute('video-id', '9bZkp7q19f0');
      document.body.append(watch);
      watch.append(panel);
    }
    if (kind === 'unstable') nativeErrorCode = 'NATIVE_TRANSCRIPT_UNSTABLE';
    await expect(fetchPageTranscript('dQw4w9WgXcQ', domTrack, 1)).resolves.toMatchObject({ ok: false });
  });

  it.each(['text-change', 'navigation', 'panel-removed'])('rejects DOM fallback after %s during the quiet period', async (kind) => {
    const panel = renderVisibleTranscript();
    const pending = fetchPageTranscript('dQw4w9WgXcQ', domTrack, 1);
    window.setTimeout(() => {
      if (kind === 'text-change') panel.querySelector('.segment-text')!.textContent = 'Still loading';
      if (kind === 'navigation') {
        window.history.replaceState({}, '', '/watch?v=9bZkp7q19f0');
        window.dispatchEvent(new Event('yt-navigate-start'));
      }
      if (kind === 'panel-removed') panel.remove();
    }, 100);
    await expect(pending).resolves.toMatchObject({ ok: false });
  });

  it('returns video context to the popup request with every available track', async () => {
    const response = await new Promise<unknown>((resolve) => {
      onRuntimeMessage?.({ type: 'GET_VIDEO_CONTEXT' }, {}, resolve);
    });
    expect(response).toMatchObject({ ok: true, data: { videoId: 'dQw4w9WgXcQ', tracks: [{ languageCode: 'en' }, { languageCode: 'vi' }] } });
  });

  it('returns the clear no-caption error', async () => {
    snapshot = { videoDetails: { videoId: 'dQw4w9WgXcQ', title: 'No captions' }, captions: { playerCaptionsTracklistRenderer: { captionTracks: [] } } };
    await expect(getVideoContext()).resolves.toMatchObject({ ok: false, error: { code: 'NO_CAPTIONS', message: 'Video này không có phụ đề khả dụng.' } });
  });

  it('waits for player data that matches the URL after SPA navigation', async () => {
    const currentSnapshot = snapshot;
    snapshot = {
      videoDetails: { videoId: '9bZkp7q19f0', title: 'Old video' },
      captions: { playerCaptionsTracklistRenderer: { captionTracks: [] } },
    };
    window.addEventListener('ezsubtitle:page-request', function replaceAfterFirstRequest(event) {
      const request = (event as CustomEvent<{ action: string }>).detail;
      if (request.action !== 'GET_SNAPSHOT' || snapshotRequests < 1) return;
      snapshot = currentSnapshot;
      window.removeEventListener('ezsubtitle:page-request', replaceAfterFirstRequest);
    });

    await expect(getVideoContext()).resolves.toMatchObject({
      ok: true,
      data: { videoId: 'dQw4w9WgXcQ', title: 'Fixture video' },
    });
    expect(snapshotRequests).toBeGreaterThan(1);
  });

  it('notifies the background when YouTube SPA navigation changes video', () => {
    window.history.pushState({}, '', '/watch?v=9bZkp7q19f0');
    window.dispatchEvent(new Event('yt-navigate-finish'));
    expect(sendMessage).toHaveBeenCalledWith({ type: 'YOUTUBE_NAVIGATED', videoId: '9bZkp7q19f0' });
  });

  it('does not call an empty endpoint response missing timestamps', async () => {
    const track = {
      id: '.en', languageCode: 'en', label: 'English',
      baseUrl: 'https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=en', isAutoGenerated: false,
    };
    await expect(fetchPageTranscript('dQw4w9WgXcQ', track)).resolves.toMatchObject({
      ok: false, error: { code: 'EMPTY_RESPONSE' },
    });
  });

  it('uses MISSING_TIMESTAMP only when the endpoint contains actual untimed text', async () => {
    endpointBody = JSON.stringify({ transcriptSegmentRenderer: { snippet: { simpleText: 'Untimed text' } } });
    const track = {
      id: '.en', languageCode: 'en', label: 'English',
      baseUrl: 'https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=en', isAutoGenerated: false,
    };
    await expect(fetchPageTranscript('dQw4w9WgXcQ', track)).resolves.toMatchObject({
      ok: false, error: { code: 'MISSING_TIMESTAMP' },
    });
  });

  it('uses timestamped segments rendered by YouTube native transcript when raw endpoints fail', async () => {
    nativeSegments = [{ startMs: 6_878, text: 'Vào tháng 7 năm 2025,' }];
    const track = {
      id: '.vi', languageCode: 'vi', label: 'Tiếng Việt',
      baseUrl: 'https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=vi', isAutoGenerated: false,
    };

    await expect(fetchPageTranscript('dQw4w9WgXcQ', track, 1)).resolves.toMatchObject({
      ok: true,
      data: { segments: [{ startMs: 6_878, text: 'Vào tháng 7 năm 2025,' }] },
    });
    expect(nativeIsOnlyTrack).toBe(true);
  });
});
