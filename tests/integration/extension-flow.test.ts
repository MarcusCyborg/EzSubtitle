import { beforeEach, describe, expect, it, vi } from 'vitest';
import { fillComposer } from '../../src/lib/chatgpt/composer-adapter';
import { fetchTranscriptForTrack } from '../../src/lib/transcript/fetch-transcript';
import { attachDraftToTab, claimDraftForTab, createPendingDraft, removeClaimedDraft } from '../../src/lib/storage/pending-draft';

const sessionData: Record<string, unknown> = {};

beforeEach(() => {
  for (const key of Object.keys(sessionData)) delete sessionData[key];
  Object.defineProperty(globalThis, 'chrome', {
    configurable: true,
    value: {
      storage: {
        session: {
          get: vi.fn(async (key: string) => ({ [key]: sessionData[key] })),
          set: vi.fn(async (values: Record<string, unknown>) => Object.assign(sessionData, values)),
          remove: vi.fn(async (key: string) => { delete sessionData[key]; }),
        },
      },
    },
  });
});

describe('extension integration mocks', () => {
  it('allows a pending ChatGPT draft to be claimed only by its created tab', async () => {
    const draft = await createPendingDraft('all transcript content');
    const secondDraft = await createPendingDraft('second transcript content');
    await attachDraftToTab(draft.token, 42);
    await attachDraftToTab(secondDraft.token, 43);

    expect(await claimDraftForTab(41)).toBeNull();
    expect(await claimDraftForTab(42)).toMatchObject({ token: draft.token, content: 'all transcript content' });
    expect(await claimDraftForTab(43)).toMatchObject({ token: secondDraft.token, content: 'second transcript content' });
    await removeClaimedDraft(draft.token, 41);
    expect(await claimDraftForTab(42)).not.toBeNull();
    await removeClaimedDraft(draft.token, 42);
    expect(await claimDraftForTab(42)).toBeNull();
  });

  it('refuses an untrusted caption URL before calling fetch', async () => {
    const transport = vi.fn();
    await expect(fetchTranscriptForTrack({
      id: 'bad', languageCode: 'en', label: 'English', baseUrl: 'https://evil.example/api/timedtext', isAutoGenerated: false,
    }, transport)).rejects.toMatchObject({ code: 'INVALID_CAPTION_URL' });
    expect(transport).not.toHaveBeenCalled();
  });

  it('fetches a newly selected caption track instead of reusing a previous language', async () => {
    const transportMock = vi.fn(async (input: RequestInfo | URL) => new Response(JSON.stringify({ events: [{
      tStartMs: 1000,
      segs: [{ utf8: String(input).includes('lang=vi') ? 'Xin chào' : 'Hello' }],
    }] })));
    const transport = transportMock as unknown as typeof fetch;
    const english = { id: '.en', languageCode: 'en', label: 'English', baseUrl: 'https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=en', isAutoGenerated: false };
    const vietnamese = { ...english, id: '.vi', languageCode: 'vi', label: 'Tiếng Việt', baseUrl: 'https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=vi' };

    await expect(fetchTranscriptForTrack(english, transport)).resolves.toEqual([{ startMs: 1000, text: 'Hello' }]);
    await expect(fetchTranscriptForTrack(vietnamese, transport)).resolves.toEqual([{ startMs: 1000, text: 'Xin chào' }]);
    expect(transportMock).toHaveBeenCalledTimes(2);
  });

  it('fills the composer but never invokes a Send button', () => {
    document.body.innerHTML = '<textarea data-id="root"></textarea><button id="send">Send</button>';
    const send = document.querySelector<HTMLButtonElement>('#send')!;
    const click = vi.spyOn(send, 'click');
    const composer = document.querySelector<HTMLTextAreaElement>('textarea')!;

    expect(fillComposer(composer, 'draft including every subtitle line')).toBe(true);
    expect(composer.value).toBe('draft including every subtitle line');
    expect(click).not.toHaveBeenCalled();
  });
});
