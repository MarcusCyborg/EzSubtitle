import type { CaptionTrack } from '../../types/transcript';

type PlayerCaptionTrack = {
  baseUrl?: unknown;
  languageCode?: unknown;
  name?: { simpleText?: unknown; runs?: Array<{ text?: unknown }> };
  vssId?: unknown;
  kind?: unknown;
};

function labelFromName(name: PlayerCaptionTrack['name'], fallback: string): string {
  if (!name || typeof name !== 'object') return fallback;
  if (typeof name.simpleText === 'string' && name.simpleText.trim()) return name.simpleText.trim();
  if (Array.isArray(name.runs)) {
    const label = name.runs.map((run) => typeof run.text === 'string' ? run.text : '').join('').trim();
    if (label) return label;
  }
  return fallback;
}

export function isTrustedCaptionUrl(value: string): boolean {
  try {
    const url = new URL(value);
    const allowedHostnames = new Set(['www.youtube.com', 'youtube.com', 'www.youtube-nocookie.com']);
    return url.protocol === 'https:'
      && allowedHostnames.has(url.hostname.toLowerCase())
      && url.pathname === '/api/timedtext';
  } catch {
    return false;
  }
}

export function captionUrlMatchesVideoId(value: string, videoId: string): boolean {
  if (!isTrustedCaptionUrl(value)) return false;
  const url = new URL(value);
  const urlVideoId = url.searchParams.get('v');
  return !urlVideoId || urlVideoId === videoId;
}

export function captionTracksFromPlayerResponse(response: unknown): CaptionTrack[] {
  if (!response || typeof response !== 'object') return [];
  const root = response as { captions?: { playerCaptionsTracklistRenderer?: { captionTracks?: unknown } } };
  const rawTracks = root.captions?.playerCaptionsTracklistRenderer?.captionTracks;
  if (!Array.isArray(rawTracks)) return [];

  const tracks: CaptionTrack[] = [];
  for (const raw of rawTracks) {
    if (!raw || typeof raw !== 'object') continue;
    const track = raw as PlayerCaptionTrack;
    if (typeof track.baseUrl !== 'string' || !isTrustedCaptionUrl(track.baseUrl)) continue;
    if (typeof track.languageCode !== 'string' || !track.languageCode.trim()) continue;
    const id = typeof track.vssId === 'string' && track.vssId ? track.vssId : track.baseUrl;
    const isAutoGenerated = track.kind === 'asr' || id.startsWith('a.');
    const languageCode = track.languageCode.trim();
    tracks.push({
      id,
      languageCode,
      label: labelFromName(track.name, languageCode),
      baseUrl: track.baseUrl,
      isAutoGenerated,
    });
  }
  return tracks;
}

export function selectDefaultTrack(tracks: CaptionTrack[]): CaptionTrack | null {
  const manualEnglish = tracks.find((track) => !track.isAutoGenerated && track.languageCode.toLowerCase().startsWith('en'));
  if (manualEnglish) return manualEnglish;
  const autoEnglish = tracks.find((track) => track.isAutoGenerated && track.languageCode.toLowerCase().startsWith('en'));
  return autoEnglish ?? tracks[0] ?? null;
}

export function captionTrackDisplayLabel(track: Pick<CaptionTrack, 'label' | 'isAutoGenerated'>): string {
  const label = track.label.trim();
  if (!track.isAutoGenerated || /(?:auto(?:matic(?:ally)?|generated)?|tự\s*động)/iu.test(label)) return label;
  return `${label} (tự động)`;
}
